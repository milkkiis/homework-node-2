// Подключаем пакет is-even: проверяет, чётное ли число
const isEven = require("is-even");
// Подключаем lodash: библиотеку утилит
const _ = require("lodash");

// Проверяем чётность числа 4 и выводим результат
console.log(`Число 4 четное? ${isEven(4)}`);
// _.uniq удаляет повторяющиеся значения из массива
console.log(`Уникальные значения: ${_.uniq([1, 2, 2, 3, 4, 4])}`);
